def render_choices(stage: str) -> str:
    """显示当前阶段的回答方向。"""

    options = GUIDANCE.get(stage)

    if options is None:
        return ""

    lines = ["\n不知道怎么回答？请选择一个方向："]

    for number, (title, _) in options.items():
        lines.append(f"  {number}. {title}")

    lines.append(
        "\n输入1-5可查看具体提示；"
        "也可以不选，直接描述自己的真实经历。"
    )

    return "\n".join(lines)


def explain_choice(
    stage: str,
    user_input: str,
) -> str | None:
    """
    数字选项只展示提示，不自动填写用户经历。

    返回None表示用户输入的是正常文本，
    应交给Agent处理。
    """

    text = user_input.strip()

    if stage not in GUIDANCE:
        return None

    if text not in {"1", "2", "3", "4", "5"}:
        return None

    title, description = GUIDANCE[stage][text]

    return (
        f"你选择了：{title}\n\n"
        f"{description}\n\n"
        "上面只是表达示例，不是你的个人经历。\n"
        "请根据真实情况写一段自己的描述。"
    )
